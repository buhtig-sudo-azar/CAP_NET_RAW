/*
 * sniffer.c — программа для захвата сырых Ethernet-пакетов и сохранения в pcap-формат.
 * Компилировать: gcc -o sniffer sniffer.c
 * Запускать только с root-правами (из-за raw socket).
 * Аргументы: [файл_дампа] [интерфейс] (оба опциональны).
 */

#include <stdio.h>      // для printf, fopen, fwrite, fflush, perror
#include <stdlib.h>     // для exit (не используется, но стандартно)
#include <string.h>     // для strcmp, strncpy, memset
#include <unistd.h>     // для close
#include <sys/socket.h> // для socket, bind, recvfrom, констант AF_PACKET, SOCK_RAW
#include <arpa/inet.h>  // для htons (преобразование порядка байт)
#include <net/ethernet.h> // для ETH_P_ALL (все протоколы Ethernet)
#include <netpacket/packet.h> // для struct sockaddr_ll (адрес канального уровня)
#include <net/if.h>      // для struct ifreq, IFNAMSIZ (запросы интерфейсов)
#include <sys/ioctl.h>   // для ioctl (управление устройствами)
#include <sys/time.h>    // для gettimeofday, struct timeval (точное время)
#include <time.h>        // для совместимости (иногда требуется)

int main(int argc, char *argv[]) {
    // argc — количество аргументов командной строки (всегда >=1)
    // argv — массив строк: argv[0] — имя программы, argv[1] — первый аргумент и т.д.

    // ----------------------------------------------------------
    // Значения по умолчанию
    // ----------------------------------------------------------
    const char *output_file = "/data/dump.pcap";  // куда сохранять дамп (в контейнере это /data)
    const char *interface = "eth0";                // какой сетевой интерфейс слушать

    // ----------------------------------------------------------
    // Разбор аргументов командной строки
    // ----------------------------------------------------------
    // Если передан хотя бы один аргумент, первый аргумент заменяет имя файла
    if (argc > 1) output_file = argv[1];
    // Если передано два аргумента, второй заменяет интерфейс
    if (argc > 2) interface = argv[2];

    // Печатаем параметры запуска (для отладки)
    printf("[C] Сниффер запущен\n");
    printf("[C] Интерфейс: %s\n", interface);
    printf("[C] Дамп: %s\n", output_file);

    // ----------------------------------------------------------
    // Открываем raw socket (сырой сокет)
    // ----------------------------------------------------------
    // socket() создаёт конечную точку связи. Возвращает файловый дескриптор (int).
    // AF_PACKET — семейство адресов канального уровня (Ethernet).
    // SOCK_RAW — тип сокета: сырой, получаем пакеты целиком, включая заголовки.
    // htons(ETH_P_ALL) — третий аргумент — протокол. ETH_P_ALL = 0x0003 (все пакеты).
    // htons() переводит число из порядка хоста (little-endian на x86) в сетевой (big-endian).
    int sock = socket(AF_PACKET, SOCK_RAW, htons(ETH_P_ALL));
    if (sock < 0) {  // если сокет не создался (обычно из-за отсутствия прав root)
        perror("[C] socket");  // выводим причину ошибки (например, "Operation not permitted")
        return 1;               // завершаем программу с кодом ошибки 1
    }

    // ----------------------------------------------------------
    // Привязываемся к конкретному интерфейсу (если нужно)
    // ----------------------------------------------------------
    // Если интерфейс не равен "все" и не "all", то привязываемся.
    // strcmp сравнивает две строки и возвращает 0, если они равны.
    if (strcmp(interface, "все") != 0 && strcmp(interface, "all") != 0) {
        // struct ifreq — структура для запроса информации об интерфейсе (определена в net/if.h)
        struct ifreq ifr;
        // memset забивает всю структуру нулями (чтобы не было мусора)
        memset(&ifr, 0, sizeof(ifr));
        // strncpy копирует имя интерфейса в поле ifr_name, не более IFNAMSIZ-1 байт
        strncpy(ifr.ifr_name, interface, IFNAMSIZ-1);

        // ioctl — системный вызов для управления устройствами.
        // sock — наш сокет, SIOCGIFINDEX — команда "получить индекс интерфейса",
        // &ifr — структура, куда будет записан результат (поле ifr_ifindex).
        if (ioctl(sock, SIOCGIFINDEX, &ifr) == -1) {
            perror("[C] ioctl");
            close(sock);   // закрываем сокет перед выходом
            return 1;
        }

        // struct sockaddr_ll — структура адреса для канального уровня (packet socket).
        struct sockaddr_ll sll;
        memset(&sll, 0, sizeof(sll));
        sll.sll_family = AF_PACKET;          // семейство адресов
        sll.sll_ifindex = ifr.ifr_ifindex;   // индекс интерфейса, полученный через ioctl
        sll.sll_protocol = htons(ETH_P_ALL); // протокол (те же все)

        // bind привязывает сокет к конкретному адресу (интерфейсу).
        // После bind этот сокет будет получать пакеты только с указанного интерфейса.
        if (bind(sock, (struct sockaddr*)&sll, sizeof(sll)) < 0) {
            perror("[C] bind");
            close(sock);
            return 1;
        }
    }

    // ----------------------------------------------------------
    // Открываем файл для записи дампа в бинарном режиме
    // ----------------------------------------------------------
    // fopen — открытие файла. "wb" — write binary (запись в бинарном режиме).
    FILE *pcap = fopen(output_file, "wb");
    if (!pcap) {  // если не удалось открыть (например, нет прав на запись)
        perror("[C] fopen");
        close(sock);
        return 1;
    }

    // ----------------------------------------------------------
    // Пишем глобальный заголовок pcap (24 байта)
    // ----------------------------------------------------------
    // Формат pcap (используется Wireshark, tcpdump) требует этот заголовок в начале файла.
    // Поля:
    // - magic (4 байта) — магическое число, определяет порядок байт (0xa1b2c3d4 = host order)
    // - version_major (2 байта) — основная версия (обычно 2)
    // - version_minor (2 байта) — минорная версия (обычно 4)
    // - thiszone (4 байта) — смещение временной зоны (0 = UTC)
    // - sigfigs (4 байта) — точность временных меток (обычно 0)
    // - snaplen (4 байта) — максимальная длина сохраняемого пакета (65535 = весь)
    // - network (4 байта) — тип канального уровня (1 = Ethernet)
    unsigned int magic = 0xa1b2c3d4;
    unsigned short version_major = 2;
    unsigned short version_minor = 4;
    unsigned int thiszone = 0;
    unsigned int sigfigs = 0;
    unsigned int snaplen = 65535;
    unsigned int network = 1; // 1 = Ethernet

    // fwrite — запись бинарных данных в файл.
    // Аргументы: указатель на данные, размер одного элемента, количество элементов, файл.
    fwrite(&magic, 4, 1, pcap);
    fwrite(&version_major, 2, 1, pcap);
    fwrite(&version_minor, 2, 1, pcap);
    fwrite(&thiszone, 4, 1, pcap);
    fwrite(&sigfigs, 4, 1, pcap);
    fwrite(&snaplen, 4, 1, pcap);
    fwrite(&network, 4, 1, pcap);

    // ----------------------------------------------------------
    // Буфер для приёма пакетов
    // ----------------------------------------------------------
    // Массив байт размером 65536 (64 КБ) — больше максимального Ethernet-кадра.
    unsigned char buffer[65536];

    printf("[C] Начинаю захват пакетов... (Ctrl+C для остановки)\n");

    // ----------------------------------------------------------
    // Основной цикл захвата пакетов
    // ----------------------------------------------------------
    while (1) {  // бесконечный цикл, выход по Ctrl+C
        // struct sockaddr_ll для получения адреса отправителя (не используем, но функция требует)
        struct sockaddr_ll addr;
        socklen_t addr_len = sizeof(addr);  // размер структуры

        // recvfrom — читает пакет из сокета.
        // Аргументы:
        //   sock — дескриптор сокета
        //   buffer — куда положить данные
        //   sizeof(buffer) — максимальный размер
        //   0 — флаги (обычные)
        //   (struct sockaddr*)&addr — сюда запишется адрес отправителя
        //   &addr_len — размер структуры (передаётся и возвращается)
        int bytes = recvfrom(sock, buffer, sizeof(buffer), 0,
                             (struct sockaddr*)&addr, &addr_len);
        if (bytes <= 0) {  // если ошибка или 0 байт (обычно не бывает)
            if (bytes < 0) perror("[C] recvfrom");
            continue;      // пропускаем итерацию и продолжаем слушать
        }

        // ----------------------------------------------------------
        // Получаем текущее время с микросекундами
        // ----------------------------------------------------------
        // struct timeval — содержит tv_sec (секунды) и tv_usec (микросекунды)
        struct timeval tv;
        gettimeofday(&tv, NULL);  // NULL — часовой пояс не нужен

        // ----------------------------------------------------------
        // Готовим заголовок пакета для pcap (16 байт)
        // ----------------------------------------------------------
        // Каждый пакет в pcap-файле имеет свой заголовок:
        // - ts_sec (4 байта) — секунды с эпохи (1970-01-01)
        // - ts_usec (4 байта) — микросекунды
        // - incl_len (4 байта) — сколько байт пакета реально сохранено
        // - orig_len (4 байта) — исходная длина пакета (если не обрезали, равно incl_len)
        unsigned int ts_sec = tv.tv_sec;
        unsigned int ts_usec = tv.tv_usec;
        unsigned int incl_len = bytes;
        unsigned int orig_len = bytes;

        // Записываем заголовок пакета
        fwrite(&ts_sec, 4, 1, pcap);
        fwrite(&ts_usec, 4, 1, pcap);
        fwrite(&incl_len, 4, 1, pcap);
        fwrite(&orig_len, 4, 1, pcap);

        // Записываем сами данные пакета (сырые байты)
        fwrite(buffer, 1, bytes, pcap);

        // fflush принудительно сбрасывает буферы файла на диск.
        // Это гарантирует, что данные не потеряются при аварийном завершении.
        fflush(pcap);

        // Выводим счётчик байт с возвратом каретки (\r), чтобы цифры обновлялись на одной строке.
        printf("[C] Пакет: %d байт\r", bytes);
    }

    // ----------------------------------------------------------
    // Закрытие (никогда не выполняется, т.к. цикл бесконечный)
    // ----------------------------------------------------------
    fclose(pcap);
    close(sock);
    return 0;
}