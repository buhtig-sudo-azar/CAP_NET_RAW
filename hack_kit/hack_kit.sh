#!/bin/bash
# ЭТО Shebang (произносится "ши-бэнг")
# #! - magic number, говорит системе: "запускай это через /bin/bash"
# Без этой строки система не поймет, какой интерпретатор использовать

# ==============================================
# ХАКЕРСКИЙ ЛАБОРАТОРНЫЙ КИТ - ЯДРО
# Версия: 1.0
# ==============================================

# -------------------- КОНФИГУРАЦИЯ --------------------

# РАЗБИРАЕМ ЭТУ СТРОКУ ПО КУСОЧКАМ:
# "${BASH_SOURCE[0]}" - специальный массив, где [0] - имя текущего скрипта
# $( ... ) - командная подстановка: результат команды внутри становится значением
# dirname - утилита, которая отрезает имя файла от пути (dirname /a/b/c.txt → /a/b)
# cd - перейти в директорию
# && - логическое "И": следующая команда выполнится, только если предыдущая успешно
# pwd - print working directory (напечатать текущую директорию)
# Всё вместе: получаем абсолютный путь к папке, где лежит скрипт
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# Просто склеиваем строки: путь + "/modules"
# Кавычки обязательны, если в пути есть пробелы
MODULES_DIR="$SCRIPT_DIR/modules"

# Ещё одна склейка строк
JOURNAL_FILE="$SCRIPT_DIR/hack_history.json"

# -------------------- ЦВЕТА ДЛЯ ВЫВОДА --------------------

# [ -t 1 ] - это КОМАНДА test с опцией -t
# Структура: if [ условие ]; then ... fi
# [ - это синоним команды test, ] - обязательная закрывающая скобка
# -t 1 - проверяет, является ли файловый дескриптор 1 (stdout) терминалом
if [ -t 1 ]; then
    # \033 - escape-символ в восьмеричном формате (ASCII 27)
    # [0;31m - CSI (Control Sequence Introducer) последовательность
    # 0 - сбросить все атрибуты, 31 - красный текст
    # Точка с запятой разделяет параметры
    RED='\033[0;31m'      # Красный
    GREEN='\033[0;32m'    # Зелёный
    YELLOW='\033[1;33m'   # 1 - жирный, 33 - жёлтый
    BLUE='\033[0;34m'     # Синий
    NC='\033[0m'          # No Color - сброс всех атрибутов
else
    # Если не терминал - просто пустые строки (чтобы не выводить мусор)
    RED=''
    GREEN=''
    YELLOW=''
    BLUE=''
    NC=''
fi
# fi - закрывает if (это if наоборот)

# ==============================================
# БАЗОВЫЕ ФУНКЦИИ
# ==============================================

# ------------------------------------------------------
# Очистка системы от всех контейнеров и образов Podman
# ------------------------------------------------------
# function имя() { ... } - объявление функции
cleanup() {
    # echo -e - включает интерпретацию escape-последовательностей (чтобы \033 работало)
    # ${YELLOW} и ${NC} - подстановка переменных с цветами
    echo -e "${YELLOW}[*] Очистка системы...${NC}"
    
    # podman rm -fa
    #   rm  - remove (удалить контейнеры)
    #   -f  - force (принудительно, даже если работают)
    #   -a  - all (все контейнеры)
    # 2>/dev/null - перенаправление stderr (поток ошибок) в /dev/null
    # 2 - номер потока stderr, > - перенаправить, /dev/null - "черная дыра" Unix
    podman rm -fa 2>/dev/null
    
    # rmi - remove image (удалить образы)
    podman rmi -fa 2>/dev/null
    
    # system prune - удалить неиспользуемые данные
    podman system prune -f 2>/dev/null
    
    echo -e "${GREEN}[✓] Система чиста${NC}"
}
# } - закрывает функцию

# ------------------------------------------------------
# Запись эксперимента в JSON-журнал
# ------------------------------------------------------
# Функция с параметрами: $1, $2, $3... - это позиционные параметры
# local - объявляет локальную переменную (видна только внутри функции)
log_experiment() {
    # Присваиваем локальным переменным значения параметров
    local action="$1"           # $1 - первый аргумент функции
    local topic="$2"            # $2 - второй аргумент
    local experiment="$3"       # $3 - третий
    local container_name="$4"    # $4 - четвертый
    local dockerfile="$5"        # $5 - пятый
    local result="$6"            # $6 - шестой
    local output_summary="$7"    # $7 - седьмой
    local project_sync="$8"      # $8 - восьмой
    
    # Экранируем кавычки через sed
    # sed - Stream EDitor
    # s/pattern/replacement/g - замена (substitute)
    # /g - global (все вхождения в строке)
    # 's/"/\\"/g' - заменить " на \"
    # $(echo ... | sed ...) - передаем echo в sed через пайп (|)
    action=$(echo "$action" | sed 's/"/\\"/g')
    topic=$(echo "$topic" | sed 's/"/\\"/g')
    experiment=$(echo "$experiment" | sed 's/"/\\"/g')
    container_name=$(echo "$container_name" | sed 's/"/\\"/g')
    dockerfile=$(echo "$dockerfile" | sed 's/"/\\"/g')
    result=$(echo "$result" | sed 's/"/\\"/g')
    output_summary=$(echo "$output_summary" | sed 's/"/\\"/g')
    project_sync=$(echo "$project_sync" | sed 's/"/\\"/g')
    
    # Формируем JSON-строку
    # ' - открывает строку в одинарных кавычках (внутри них всё буквально)
    # "'"$action"'" - хитрый прием:
    #   ' - выходим из строки
    #   "'" - открываем двойные кавычки, вставляем переменную, закрываем двойные
    #   ' - возвращаемся в строку
    # Получается: "action": "значение"
    local log_entry='{
        "action": "'"$action"'",
        "topic": "'"$topic"'",
        "experiment": "'"$experiment"'",
        "container_name": "'"$container_name"'",
        "dockerfile": "'"$dockerfile"'",
        "result": "'"$result"'",
        "output_summary": "'"$output_summary"'",
        "project_sync": "'"$project_sync"'"
    }'
    
    # Проверяем существование файла
    # [ -f "$JOURNAL_FILE" ] - проверка: существует ли файл (-f)
    if [ -f "$JOURNAL_FILE" ]; then
        # Файл есть - добавляем запись
        
        # sed -i.bak - in-place с созданием бэкапа
        # '$' - адрес: последняя строка файла
        # s/}$/},/ - замена: ищем } в конце строки, меняем на },
        sed -i.bak '$ s/}$/},/' "$JOURNAL_FILE" 2>/dev/null && rm -f "$JOURNAL_FILE.bak"
        # && - выполняем rm только если sed успешно отработал
        
        # >> - дописать в конец файла (двойной >)
        echo "$log_entry" >> "$JOURNAL_FILE"
        # Закрываем JSON-массив
        echo "]" >> "$JOURNAL_FILE"
    else
        # Файла нет - создаём новый
        # > - записать в файл (одинарный >), перезаписывает если файл есть
        echo '[' > "$JOURNAL_FILE"
        echo "$log_entry" >> "$JOURNAL_FILE"
        echo ']' >> "$JOURNAL_FILE"
    fi
    
    echo -e "${GREEN}[✓] Записано в журнал: $action | $topic${NC}"
}

# ------------------------------------------------------
# Показать содержимое журнала
# ------------------------------------------------------
show_journal() {
    if [ -f "$JOURNAL_FILE" ]; then
        echo
        echo "=== ЖУРНАЛ ЭКСПЕРИМЕНТОВ ==="
        echo
        
        # command -v jq - проверяет, существует ли команда jq в системе
        # >/dev/null 2>&1 - перенаправляем stdout и stderr в никуда
        # 2>&1 - stderr (2) перенаправить туда же, куда и stdout (1)
        if command -v jq >/dev/null 2>&1; then
            # jq '.' - вывести JSON в красиво отформатированном виде
            jq '.' "$JOURNAL_FILE"
        else
            # cat - вывести содержимое файла
            cat "$JOURNAL_FILE"
        fi
    else
        echo "Журнал пуст"
    fi
}

# ------------------------------------------------------
# Загрузить и запустить модуль по его номеру в меню
# ------------------------------------------------------
run_module() {
    local module_num="$1"      # номер модуля из меню
    local module_file           # путь к файлу модуля
    local module_name           # имя модуля без пути и расширения
    
    # Ищем файл модуля по номеру
    # Цикл for: for переменная in список; do ... done
    # "$MODULES_DIR"/*.sh - шаблон (wildcard), раскрывается в список .sh файлов
    local i=1
    for module in "$MODULES_DIR"/*.sh; do
        # [ -f "$module" ] - проверяем, что это файл (а не пустой шаблон)
        if [ -f "$module" ]; then
            if [ "$i" -eq "$module_num" ]; then
                # -eq - числовое сравнение (equal)
                module_file="$module"
                # basename - утилита, отрезает путь
                module_name=$(basename "$module" .sh)  # .sh - суффикс для удаления
                break  # выходим из цикла
            fi
            ((i++))  # увеличение счетчика в арифметическом контексте
        fi
    done
    
    # [ -n "$module_file" ] - проверка: строка не пустая (-n)
    if [ -n "$module_file" ]; then
        echo -e "${BLUE}[*] Запуск модуля: $module_name${NC}"
        
        # source - выполняет файл в текущем контексте (загружает функции)
        source "$module_file"
        
        # declare -f run - проверяет, объявлена ли функция run
        # > /dev/null - перенаправляем вывод в никуда
        if declare -f run > /dev/null; then
            # Запускаем функцию run из модуля
            run
        else
            echo -e "${RED}[✗] В модуле $module_name нет функции run()${NC}"
            echo "Модуль должен содержать функцию run() для запуска эксперимента"
        fi
    else
        echo -e "${RED}[✗] Модуль $module_num не найден${NC}"
    fi
}

# ==============================================
# МЕНЮ
# ==============================================

# ------------------------------------------------------
# Показать интерактивное меню
# ------------------------------------------------------
show_menu() {
    echo
    echo "=== ХАКЕРСКИЙ ЛАБОРАТОРНЫЙ КИТ ==="
    echo
    echo "ЯДРО"
    echo "  c) Очистка системы"
    echo
    echo "МОДУЛИ"
    
    # Проверяем, есть ли модули в папке
    # -d "$MODULES_DIR" - проверка: существует ли директория
    # ls -A - показать все файлы, включая скрытые, но без . и ..
    # $( ... ) - подстановка результата команды
    if [ -d "$MODULES_DIR" ] && [ "$(ls -A "$MODULES_DIR" 2>/dev/null)" ]; then
        local i=1
        for module in "$MODULES_DIR"/*.sh; do
            if [ -f "$module" ]; then
                name=$(basename "$module" .sh)
                echo "  $i) $name"
                ((i++))
            fi
        done
    else
        echo "  (нет модулей — идём по плану)"
    fi
    
    echo
    echo "  j) Показать журнал"
    echo "  q) Выход"
    echo
    # echo -n - не переводить строку в конце
    echo -n "Выбери опцию: "
}

# ==============================================
# ГЛАВНЫЙ ЦИКЛ
# ==============================================

# mkdir -p - создать директорию, включая все промежуточные (-p = parents)
# Если директория уже есть - не ругается
mkdir -p "$MODULES_DIR"

# Обработка аргументов командной строки
# $1 - первый аргумент скрипта
if [ "$1" = "cleanup" ]; then
    cleanup
    exit 0  # exit с кодом 0 (успешное завершение)
fi

# Интерактивный режим (бесконечный цикл)
while true; do
    show_menu
    
    # read -r choice - читаем строку в переменную choice
    # -r - raw mode (не интерпретировать обратные слеши)
    read -r choice
    
    # case - множественный выбор
    # in - начинаем перебор вариантов
    # ;; - конец блока для текущего варианта
    # * ) - вариант по умолчанию (любой другой ввод)
    case "$choice" in
        c|C)
            # | - ИЛИ: подходит либо c, либо C
            cleanup
            ;;
        [0-9]*)
            # [0-9]* - любой ввод, начинающийся с цифры
            # Проверяем, что это число и оно >= 1
            # 2>/dev/null - подавляем ошибку, если это не число
            if [ "$choice" -ge 1 ] 2>/dev/null; then
                # Подсчитываем количество модулей
                # ls -1 - по одному файлу в строке
                # wc -l - word count, подсчет строк (-l = lines)
                max_modules=$(ls -1 "$MODULES_DIR"/*.sh 2>/dev/null | wc -l)
                
                # -le - less or equal (меньше или равно)
                # -gt - greater than (больше)
                if [ "$choice" -le "$max_modules" ] && [ "$max_modules" -gt 0 ]; then
                    run_module "$choice"
                else
                    echo -e "${RED}[✗] Модуль $choice не существует${NC}"
                fi
            else
                echo -e "${RED}[✗] Неверный выбор${NC}"
            fi
            ;;
        j|J)
            show_journal
            ;;
        q|Q)
            echo "Выход"
            exit 0
            ;;
        *)
            # * - любой другой ввод (default)
            echo -e "${RED}[✗] Неверный выбор${NC}"
            ;;
    esac
    # esac - закрывает case (case наоборот)
    
    # Пауза перед следующим показом меню
    echo
    echo -n "Нажми Enter для продолжения..."
    read
done
# done - закрывает while